from docx.enum.text import WD_ALIGN_PARAGRAPH


def set_run_font(run, size=14, bold=False, italic=False, color=None):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color


def add_para(doc, runs, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=14,
             space_after=6, first_line_indent=None):
    """runs — строка или список (text, bold)."""
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    if first_line_indent is not None:
        p.paragraph_format.first_line_indent = Cm(first_line_indent)
    if isinstance(runs, str):
        runs = [(runs, False)]
    for text, bold in runs:
        r = p.add_run(text)
        set_run_font(r, size=size, bold=bold)
    return p


def add_slide_header(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(4)
    r = p.add_run(text)
    set_run_font(r, size=13, bold=True, color=RGBColor(0x1F, 0x3A, 0x68))
    return p


def add_centered(doc, text, *, size=16, bold=True, italic=False, color=None,
                 space_after=4):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(space_after)
    r = p.add_run(text)
    set_run_font(r, size=size, bold=bold, italic=italic, color=color)
    return p


